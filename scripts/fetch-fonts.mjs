#!/usr/bin/env node
// fetch-fonts.mjs — download the site's webfonts once, and serve them ourselves.
//
// The stylesheet names VT323, Source Serif 4 and JetBrains Mono, but nothing
// ever loaded them: there was no @font-face and no CDN link, and none of the
// three is installed on a stock machine. So the site rendered in Georgia and
// Consolas while its CSS claimed otherwise. This fetches the latin subset of
// each family, writes it under site/fonts/, and emits site/fonts.css with
// local @font-face rules.
//
// Self-hosted on purpose: no third-party request per page view, and the site
// keeps its typography with no network at all.
//
// Usage:  node scripts/fetch-fonts.mjs [--force]
//   --force  re-download even if the files are already present

import { writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SITE = join(ROOT, 'site');
const OUT = join(SITE, 'fonts');
const FORCE = process.argv.includes('--force');

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FAMILIES = [
  { family: 'VT323',            query: 'VT323',                                        weights: [400] },
  { family: 'Source Serif 4',   query: 'Source+Serif+4:opsz,wght@8..60,400;8..60,600', weights: [400, 600] },
  { family: 'JetBrains Mono',   query: 'JetBrains+Mono:wght@400;600',                  weights: [400, 600] },
];

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

async function get(url, asText = true) {
  const res = await fetch(url, { headers: { 'user-agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return asText ? res.text() : Buffer.from(await res.arrayBuffer());
}

// Google emits one @font-face per subset, each preceded by a /* subset */ comment.
function parseFaces(css) {
  const faces = [];
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
  for (const m of css.matchAll(re)) {
    const [, subset, body] = m;
    const family = body.match(/font-family:\s*'([^']+)'/)?.[1];
    const weight = Number(body.match(/font-weight:\s*(\d+)/)?.[1] ?? 400);
    const url = body.match(/src:\s*url\(([^)]+)\)/)?.[1];
    const range = body.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
    if (family && url) faces.push({ subset, family, weight, url, range });
  }
  return faces;
}

mkdirSync(OUT, { recursive: true });

const wanted = [];
for (const fam of FAMILIES) {
  const css = await get(`https://fonts.googleapis.com/css2?family=${fam.query}&display=swap`);
  const faces = parseFaces(css);
  // Latin only. The other subsets (cyrillic, greek, vietnamese) would multiply
  // the download for glyphs this course never uses.
  for (const w of fam.weights) {
    const face = faces.find((f) => f.subset === 'latin' && f.weight === w);
    if (!face) throw new Error(`no latin ${w} face for ${fam.family}`);
    wanted.push({ ...face, out: `${slug(fam.family)}-${w}.woff2` });
  }
}

const rules = [];
let bytes = 0;
for (const f of wanted) {
  const target = join(OUT, f.out);
  const cached = existsSync(target) && statSync(target).size > 0;
  if (cached && !FORCE) {
    bytes += statSync(target).size;
    console.log(`  cached   ${f.out}`);
  } else {
    const buf = await get(f.url, false);
    writeFileSync(target, buf);
    bytes += buf.length;
    console.log(`  fetched  ${f.out}  (${(buf.length / 1024).toFixed(1)} KB)`);
  }
  rules.push(`@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${f.weight};
  font-display: swap;
  src: url('fonts/${f.out}') format('woff2');
  unicode-range: ${f.range};
}`);
}

// Paths are relative to fonts.css, which sits beside style.css in site/, so
// they resolve the same way at every page depth.
writeFileSync(join(SITE, 'fonts.css'), `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand.
   Latin subset only. Re-run with --force to refresh. */

${rules.join('\n\n')}
`);

console.log(`\n${wanted.length} faces, ${(bytes / 1024).toFixed(1)} KB total, written to site/fonts/`);
console.log('site/fonts.css regenerated.');
